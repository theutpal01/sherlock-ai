"""Fact records and the knowledge base.

Three fact categories (per spec section 7):
  1. case facts      -- true at case initialization
  2. observed facts  -- revealed by legitimate player discovery/testimony
  3. derived facts   -- conclusions generated by the inference engine

Provenance is mandatory for every derived fact: the rule that produced it
plus the supporting fact IDs. This is what powers the WHY? feature.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from .terms import Predicate


@dataclass
class FactRecord:
    """A single fact plus its provenance."""

    fact_id: str
    predicate: Predicate
    derived: bool = False
    rule_id: str | None = None
    supports: list[str] = field(default_factory=list)
    source: str | None = None  # evidence ID / testimony ID for observed facts
    category: str = "case"  # "case" | "observed" | "derived"

    def to_provenance_dict(self) -> dict:
        return {
            "fact": {"name": self.predicate.name, "args": list(self.predicate.args)},
            "derived": self.derived,
            "rule_id": self.rule_id,
            "supports": list(self.supports),
        }


class KnowledgeBase:
    """In-memory store of player-known facts with deduplication.

    The engine must not reason from undiscovered evidence: callers are
    responsible for only inserting observed facts the player legitimately
    discovered. This class simply stores what it is given.
    """

    def __init__(self) -> None:
        self._facts: dict[str, FactRecord] = {}
        self._predicate_to_id: dict[Predicate, str] = {}
        self._counter = 0

    def _next_id(self, category: str) -> str:
        self._counter += 1
        prefix = {"case": "F", "observed": "F", "derived": "D"}.get(category, "F")
        return f"{prefix}_{self._counter:03d}"

    def add(
        self,
        predicate: Predicate,
        category: str = "case",
        fact_id: str | None = None,
        rule_id: str | None = None,
        supports: list[str] | None = None,
        source: str | None = None,
    ) -> FactRecord:
        """Add a fact; return the existing record when the predicate is known."""
        existing_id = self._predicate_to_id.get(predicate)
        if existing_id is not None:
            return self._facts[existing_id]
        fid = fact_id or self._next_id(category)
        record = FactRecord(
            fact_id=fid,
            predicate=predicate,
            derived=(category == "derived"),
            rule_id=rule_id,
            supports=list(supports or []),
            source=source,
            category=category,
        )
        self._facts[fid] = record
        self._predicate_to_id[predicate] = fid
        return record

    def contains(self, predicate: Predicate) -> bool:
        return predicate in self._predicate_to_id

    def get_by_predicate(self, predicate: Predicate) -> FactRecord | None:
        fid = self._predicate_to_id.get(predicate)
        return self._facts[fid] if fid else None

    def get(self, fact_id: str) -> FactRecord | None:
        return self._facts.get(fact_id)

    def all_predicates(self) -> list[Predicate]:
        return [r.predicate for r in self._facts.values()]

    def all_records(self) -> list[FactRecord]:
        return list(self._facts.values())

    def __len__(self) -> int:
        return len(self._facts)
